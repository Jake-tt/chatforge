import { useCallback, useEffect, useState } from "react";
import { api, ApiError, Conversation, Me, Usage } from "./api";
import AuthDialog from "./components/AuthDialog";
import ChatPanel from "./components/ChatPanel";
import Sidebar from "./components/Sidebar";

export default function App() {
  const [me, setMe] = useState<Me | null>(null);
  const [conversations, setConversations] = useState<Conversation[]>([]);
  const [activeId, setActiveId] = useState<string | null>(null);
  // Remounts the chat panel only on explicit navigation. Creating a conversation for the
  // first message of a new chat changes activeId but must not reset the streaming panel.
  const [panelKey, setPanelKey] = useState("new");
  const [usage, setUsage] = useState<Usage | null>(null);
  const [authOpen, setAuthOpen] = useState(false);
  const [notice, setNotice] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const refresh = useCallback(async () => {
    try {
      const [meRes, convs, usageRes] = await Promise.all([
        api.me(),
        api.listConversations(),
        api.usage(),
      ]);
      setMe(meRes);
      setConversations(convs);
      setUsage(usageRes);
      setError(null);
    } catch (e) {
      setError(e instanceof ApiError ? e.message : "서버에 연결할 수 없어요.");
    }
  }, []);

  useEffect(() => {
    void refresh();
  }, [refresh]);

  const select = (id: string | null) => {
    setActiveId(id);
    setPanelKey(id ?? `new-${Date.now()}`);
  };

  const createConversation = async () => {
    const conv = await api.createConversation();
    setConversations((prev) => [conv, ...prev]);
    setActiveId(conv.id);
    return conv.id;
  };

  const deleteConversation = async (id: string) => {
    await api.deleteConversation(id);
    setConversations((prev) => prev.filter((c) => c.id !== id));
    if (activeId === id) select(null);
  };

  const onReplyFinished = async () => {
    // Titles are generated by a background job; poll briefly for it.
    setUsage(await api.usage());
    setConversations(await api.listConversations());
    setTimeout(() => void api.listConversations().then(setConversations), 2000);
  };

  const onAuthenticated = async (moved: number) => {
    setAuthOpen(false);
    select(null);
    setNotice(moved > 0 ? `게스트로 나눈 대화 ${moved}개를 계정으로 옮겼어요.` : null);
    await refresh();
  };

  const logout = async () => {
    api.logout();
    select(null);
    setNotice(null);
    await refresh();
  };

  return (
    <div className="layout">
      <Sidebar
        me={me}
        usage={usage}
        conversations={conversations}
        activeId={activeId}
        onSelect={select}
        onNew={() => select(null)}
        onDelete={(id) => void deleteConversation(id)}
        onLogin={() => setAuthOpen(true)}
        onLogout={() => void logout()}
      />
      <main className="main">
        {error && <div className="banner banner-error">{error}</div>}
        {notice && (
          <div className="banner banner-info" onClick={() => setNotice(null)}>
            {notice}
          </div>
        )}
        <ChatPanel
          key={panelKey}
          conversationId={activeId}
          isGuest={me?.kind === "guest"}
          ensureConversation={async () => activeId ?? (await createConversation())}
          onReplyFinished={() => void onReplyFinished()}
          onLoginRequested={() => setAuthOpen(true)}
        />
      </main>
      {authOpen && (
        <AuthDialog onClose={() => setAuthOpen(false)} onAuthenticated={onAuthenticated} />
      )}
    </div>
  );
}
